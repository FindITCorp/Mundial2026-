def run():
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    cur = conn.cursor()

    stats = {
        "teams_processed": 0,
        "players_updated": 0,
        "players_inserted": 0,
        "players_retired": 0,
    }

    for team_name, players in WC2026_SQUADS.items():
        team_row = cur.execute("SELECT id FROM teams WHERE name=?", (team_name,)).fetchone()
        if not team_row:
            log.warning(f"Team not found: {team_name}")
            continue

        team_id = team_row["id"]
        log.info(f"Processing {team_name} ({len(players)} players)...")

        # 1. Reset ALL players to confirmed=0 for this team (clean slate)
        cur.execute(
            "UPDATE squad_selections SET confirmed=0 WHERE team_id=?", (team_id,)
        )
        stats["players_retired"] += cur.rowcount

        # 2. Upsert players
        for (name, pos, caps, goals, age, club, league) in players:
            if club == "SKIP":
                continue

            # Try to find existing player
            existing = cur.execute(
                "SELECT id FROM players WHERE team_id=? AND name=?", (team_id, name)
            ).fetchone()

            if existing:
                # Update stats
                cur.execute(
                    """UPDATE players SET position=?, caps=?, goals_as_nat=?, age=?,
                       club=?, club_league=? WHERE id=?""",
                    (pos, caps, goals, age, club, league, existing["id"]),
                )
                # Ensure confirmed=1
                cur.execute(
                    """INSERT OR IGNORE INTO squad_selections (team_id, player_id, confirmed)
                       VALUES (?,?,1)""",
                    (team_id, existing["id"]),
                )
                cur.execute(
                    "UPDATE squad_selections SET confirmed=1 WHERE player_id=? AND team_id=?",
                    (existing["id"], team_id),
                )
                stats["players_updated"] += 1
            else:
                # Insert new player
                cur.execute(
                    """INSERT INTO players
                       (name, team_id, position, caps, goals_as_nat, age, club, club_league)
                       VALUES (?,?,?,?,?,?,?,?)""",
                    (name, team_id, pos, caps, goals, age, club, league),
                )
                new_id = cur.lastrowid
                cur.execute(
                    """INSERT OR IGNORE INTO squad_selections (team_id, player_id, confirmed)
                       VALUES (?,?,1)""",
                    (team_id, new_id),
                )
                stats["players_inserted"] += 1
                log.debug(f"  Inserted: {name} ({pos})")

        stats["teams_processed"] += 1

    conn.commit()
    conn.close()
    return stats


